#!/usr/bin/env python3
"""Turns tool output into the writeup's data files and generated figures (run by make_data.sh).

Subcommands (inputs are the raw tool outputs make_data.sh keeps in writeup/data/tmp/):
  grids DUMP OUTDIR [--prefix P] [--rename LABEL=NAME,...]   dump_range output -> one tikzpicture per spot
  distance SCRATCH_GTO SCRATCH_PTO OUT_DAT OUT_TEX            validate per-spot distances
"""
import argparse
import re
import sys
from pathlib import Path

RANKS = "AKQJT98765432"
REACH_MIN = 1e-3  # as solve --show: a class with less reach is drawn blank ("never gets here")
HEADER = "% Generated by writeup/scripts/gen.py ({}). Do not edit; rerun writeup/scripts/make_data.sh.\n"


def spot_key(label):
    """ref file stem without its source prefix: gto_open_lj -> open_lj."""
    return re.sub(r"^(gto|pto)_", "", label)


def read_dump(path):
    """dump_range lines -> {label: {class: (raise, call, reach)}}, in file order."""
    out = {}
    for line in Path(path).read_text().splitlines():
        label, cls, r, c, reach = line.split()
        out.setdefault(label, {})[cls] = (float(r), float(c), float(reach))
    return out


GRID_MACROS = r"""\providecommand{\gridunit}{0.42cm}
\providecommand{\blankcell}[3]{%
  \fill[white] (#1,-#2) rectangle ++(1,-1);
  \draw[foldcol,line width=0.3pt] (#1,-#2) rectangle ++(1,-1);
  \node[font=\fontsize{4}{4}\selectfont,inner sep=0,text=black!30] at ({#1+0.5},{-#2-0.5}) {#3};}
"""


def class_name(row, col):
    if row == col:
        return RANKS[row] * 2
    hi, lo = min(row, col), max(row, col)
    return RANKS[hi] + RANKS[lo] + ("s" if row < col else "o")


def write_grid(path, cells, source):
    lines = [HEADER.format(source), GRID_MACROS, "\\begin{tikzpicture}[x=\\gridunit,y=\\gridunit]\n"]
    for row in range(13):
        for col in range(13):
            name = class_name(row, col)
            r, c, reach = cells[name]
            if reach < REACH_MIN:
                lines.append(f"\\blankcell{{{col}}}{{{row}}}{{{name}}}\n")
            else:
                lines.append(f"\\rangecell{{{col}}}{{{row}}}{{{r:.3f}}}{{{c:.3f}}}{{{name}}}\n")
    lines.append("\\draw[black!50,line width=0.4pt] (0,0) rectangle (13,-13);\n\\end{tikzpicture}\n")
    Path(path).write_text("".join(lines))


def cmd_grids(a):
    rename = dict(kv.split("=") for kv in a.rename.split(",")) if a.rename else {}
    for label, cells in read_dump(a.dump).items():
        name = rename.get(label, a.prefix + spot_key(label))
        write_grid(Path(a.outdir) / f"{name}.tex", cells, f"{Path(a.dump).name}: {label}")


def read_validate(path):
    """validate stdout -> ({spot name: (category, distance)}, {category: score}, overall)."""
    spots, cats, overall = {}, {}, None
    for line in Path(path).read_text().splitlines():
        if m := re.match(r"(\S+)\s+spot \S+\s+distance ([\d.]+)", line):
            spots[m[1]] = float(m[2])
        elif m := re.match(r"category (\S+)\s+([\d.]+) over", line):
            cats[m[1]] = float(m[2])
        elif m := re.match(r"score ([\d.]+)", line):
            overall = float(m[1])
    return spots, cats, overall


def category(key):
    return re.match(r"(open|vs_open|vs_3bet|vs_4bet|vs_5bet)", key)[1]


def cmd_distance(a):
    gto, _, _ = read_validate(a.gto)
    pto, _, _ = read_validate(a.pto)
    keys = sorted({spot_key(k) for k in gto})
    rows = ["spot category gto pto\n"]
    tex = [HEADER.format("validate per-spot distance of Scratch"),
           "% \\spotdist{gto|pto}{spot}: Scratch's distance from that chart, e.g. \\spotdist{gto}{open_lj}.\n",
           "\\providecommand{\\spotdist}[2]{\\csname spotdist@#1@#2\\endcsname}\n"]
    for k in keys:
        g, p = gto.get("gto_" + k, float("nan")), pto.get("pto_" + k, float("nan"))
        rows.append(f"{k} {category(k)} {g:.3f} {p:.3f}\n")
        tex.append(f"\\expandafter\\def\\csname spotdist@gto@{k}\\endcsname{{{g:.3f}}}\n")
        tex.append(f"\\expandafter\\def\\csname spotdist@pto@{k}\\endcsname{{{p:.3f}}}\n")
    Path(a.out_dat).write_text("".join(rows))
    Path(a.out_tex).write_text("".join(tex))


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("grids")
    g.add_argument("dump"), g.add_argument("outdir")
    g.add_argument("--prefix", default="grid_"), g.add_argument("--rename", default="")
    d = sub.add_parser("distance")
    for x in ("gto", "pto", "out_dat", "out_tex"):
        d.add_argument(x)
    a = ap.parse_args()
    {"grids": cmd_grids, "distance": cmd_distance}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
